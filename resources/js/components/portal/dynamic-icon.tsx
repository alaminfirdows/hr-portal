export function iconFor(name: string | null | undefined): LucideIcon {
    return (name && ICONS[name]) || Circle;
}

export function DynamicIcon({
    name,
    ...props
}: { name: string | null | undefined } & LucideProps) {
    const Icon = iconFor(name);

    return <Icon {...props} />;
}
