<?php

namespace Modules\Documents\Database\Seeders;

use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Storage;
use Modules\Documents\Enums\DocumentKind;
use Modules\Documents\Enums\DocumentVisibility;
use Modules\Documents\Models\Document;
use Modules\Documents\Models\Folder;
use Modules\Employees\Models\Employee;
use Modules\Identity\Models\User;

/**
 * Three folders and 20 documents (text files on the private disk plus external links).
 */
class DocumentsDemoSeeder extends Seeder
{
    /**
     * [folder, title, category, visibility, kind, expires in days|null]
     *
     * @return list<array{string, string, string, string, string, int|null}>
     */
    private function docs(): array
    {
        return [
            ['HR', 'Employee handbook', 'Policy', 'organization', 'file', null],
            ['HR', 'Leave policy', 'Policy', 'organization', 'file', null],
            ['HR', 'Code of conduct', 'Policy', 'organization', 'file', 365],
            ['HR', 'Benefits overview', 'Benefits', 'organization', 'link', null],
            ['HR', 'Onboarding checklist', 'Onboarding', 'organization', 'file', null],
            ['HR', 'Salary bands 2026', 'Compensation', 'private', 'file', null],
            ['HR', 'Health insurance renewal', 'Benefits', 'private', 'file', 25],
            ['HR', 'Office lease agreement', 'Legal', 'private', 'file', 6],
            ['Company', 'Company overview deck', 'General', 'organization', 'file', null],
            ['Company', 'Brand guidelines', 'General', 'organization', 'link', null],
            ['Company', 'Security awareness guide', 'Policy', 'organization', 'file', 180],
            ['Company', 'Org chart', 'General', 'organization', 'link', null],
            ['Company', 'Engineering practices', 'Engineering', 'department', 'file', null],
            ['Company', 'Backend team runbook', 'Engineering', 'team', 'file', null],
            ['Company', 'Quarterly all-hands notes', 'General', 'organization', 'file', null],
            ['Projects', 'Project kickoff template', 'Template', 'organization', 'file', null],
            ['Projects', 'Client contract template', 'Legal', 'private', 'file', 28],
            ['Projects', 'Design system', 'Design', 'organization', 'link', null],
            ['Projects', 'Roadmap 2026', 'Planning', 'department', 'link', null],
            ['Projects', 'Release checklist', 'Engineering', 'organization', 'file', null],
        ];
    }

    public function run(): void
    {
        if (Document::query()->exists()) {
            return;
        }

        $hr = User::query()->where('email', 'hr@example.com')->first() ?? User::query()->first();

        if ($hr === null) {
            return;
        }

        $target = Employee::query()->where('email', 'employee@example.com')->first() ?? Employee::query()->where('user_id', $hr->id)->first();
        $folders = collect(['HR', 'Company', 'Projects'])
            ->mapWithKeys(fn (string $name) => [$name => Folder::query()->firstOrCreate(['name' => $name, 'parent_id' => null])]);
        $disk = Storage::disk((string) config('filesystems.default'));

        foreach ($this->docs() as $i => [$folder, $title, $category, $visibility, $kind, $expires]) {
            $attributes = [
                'folder_id' => $folders[$folder]->id,
                'title' => $title,
                'description' => "{$title} for the demo organization.",
                'category' => $category,
                'tags' => [strtolower($category), 'demo'],
                'kind' => DocumentKind::from($kind),
                'visibility' => DocumentVisibility::from($visibility),
                'uploaded_by' => $hr->id,
                'expires_on' => $expires === null ? null : now()->addDays($expires)->toDateString(),
                'department_id' => in_array($visibility, ['department', 'team'], true) ? $target?->department_id : null,
                'team_id' => $visibility === 'team' ? $target?->team_id : null,
            ];

            if ($kind === 'link') {
                $attributes['url'] = 'https://example.com/docs/'.str($title)->slug();
            } else {
                $name = str($title)->slug().'.txt';
                $path = "documents/demo/{$i}-{$name}";
                $body = "{$title}\n\nDemo document generated by the seeder.\n";
                $disk->put($path, $body);
                $attributes += ['file_path' => $path, 'file_name' => $name, 'mime_type' => 'text/plain', 'size' => strlen($body)];
            }

            Document::query()->create($attributes);
        }
    }
}
